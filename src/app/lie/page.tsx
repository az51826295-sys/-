/**
 * **거짓말의 온도 — 취조실** (228회차 10-01, 사장님 기획).
 *
 * 화면이 해야 하는 일은 셋이다:
 *  ① **증거를 눌러서 내민다.** 글로만 가리키게 하면 "카페 CCTV" 라고 정확히 쳐야 한다 — 그건 게임이 아니라 받아쓰기다.
 *  ② **온도를 보여 준다.** 압박·당황·분노·경계가 안 보이면 플레이어는 뭘 잘못했는지 영영 모른다.
 *     다만 **숫자는 안 보여 준다** — 막대와 말로만. 숫자가 보이면 숫자를 보고 게임하게 된다.
 *  ③ **왜 움직였는지 적는다.** "경계가 올라 증거가 덜 먹혔다" 를 알려 줘야 다음 판이 달라진다.
 *
 * 진실·약점표는 화면으로 **안 내려온다**(서버가 안 보낸다). 개발자 도구를 열어도 답이 안 보인다.
 */
import 판 from "./판";
import { 기본사건 } from "@/lib/lie/case";
import { 현장처음, 보여줄지점 } from "@/lib/lie/scene";

export const metadata = { title: "거짓말의 온도" };

const 사건 = 기본사건();

export default function Page() {
  // **플레이어가 알아도 되는 것만** 내려보낸다. 진실·약점·무너지면 은 뺀다.
  // 얼굴은 `public/lie/` 에 있다(규격: 448×448 · 가슴 위 · 취조실 조명 — `engine/work/lie/얼굴.mts`).
  const 얼굴 = { A: "/lie/han.jpg", B: "/lie/yun.jpg", C: "/lie/park.jpg" } as Record<string, string>;
  const 용의자들 = 사건.용의자.map((s) => ({ id: s.id, 이름: s.이름, 관계: s.관계, 겉모습: s.겉모습, 얼굴: 얼굴[s.id] ?? "" }));
  const 증거들 = 사건.증거.map((e) => ({ id: e.id, 이름: e.이름, 설명: e.설명 }));
  // **확인할 것** — 용의자가 한 주장 중 다른 사람에게 물어봐야 하는 것들.
  // 누구에게 물어야 하는지까지만 알려 준다. 답(반박)은 안 내려보낸다 — 그건 취조로 얻는 것이다.
  const 확인할것 = 사건.교차.map((x) => ({
    id: x.id, 주장: x.주장,
    물을사람: 사건.용의자.find((s) => s.id === x.물을사람)?.이름 ?? "",
    얻는증거id: x.생기는증거.id,
  }));
  // 현장: **답은 안 내려보낸다.** 지점 이름과 잠겼는지만(`보여줄지점`).
  const 첫상태 = 현장처음(사건);
  const 첫지점 = 보여줄지점(사건, 첫상태);
  const 곳들 = 사건.현장.곳.map((c) => ({ id: c.id, 이름: c.이름, 설명: c.설명 }));
  return (
    <판
      사건={{ 제목: 사건.제목, 피해자: 사건.피해자, 발생시각: 사건.발생시각, 장소: 사건.장소 }}
      용의자들={용의자들}
      증거들={증거들}
      확인할것={확인할것}
      곳들={곳들}
      첫지점={첫지점}
      첫상태={첫상태}
    />
  );
}
