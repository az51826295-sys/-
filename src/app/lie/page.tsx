import 취조실 from "./취조실";
import { 사건1 } from "@/lib/lie/case";

export const metadata = { title: "거짓말의 온도" };

export default function Page() {
  // **플레이어가 알아도 되는 것만** 내려보낸다. 진실·약점·무너지면 은 뺀다.
  const 용의자들 = 사건1.용의자.map((s) => ({ id: s.id, 이름: s.이름, 관계: s.관계, 겉모습: s.겉모습 }));
  const 증거들 = 사건1.증거.map((e) => ({ id: e.id, 이름: e.이름, 설명: e.설명 }));
  return (
    <취조실
      사건={{ 제목: 사건1.제목, 피해자: 사건1.피해자, 발생시각: 사건1.발생시각, 장소: 사건1.장소 }}
      용의자들={용의자들}
      증거들={증거들}
    />
  );
}
