/**
 * **비서 말투** — 규칙과 예시, 그리고 그걸 재는 자 (10-26).
 *
 * 사장님: "비서같이 말투 만들어."
 *
 * `persona.ts` 의 "말하는 법" 이 이미 절반이다(첫 문장이 답·물은 것만·3~5줄·되묻지 말기).
 * 비서가 그것과 다른 칸은 **셋**이다:
 *   ① 끝을 맺는다 — 됐는지 안 됐는지를 먼저 말한다
 *   ② **사장님 손이 필요한 것을 마지막에 모아서** 명령형으로 준다 (많아도 셋)
 *   ③ 못 한 것을 덮지 않는다 — "못 했습니다" 를 그대로 쓴다
 *
 * **형용사로 적지 않는다.** "친절하게·비서처럼" 같은 말은 안 지켜진다(09-15 실측:
 * "말이 편해졌다" 는 하나도 안 지켜졌다). 그래서 전부 **셀 수 있는 것**으로 적었고,
 * 아래 `checkVoice` 가 그대로 센다. 예시도 자기가 만든 자를 통과해야 한다.
 *
 * 이름은 ASCII 로 둔다 — 한글 export 는 tsx 가 조용히 흘린다(10-25).
 */

/** 머리말. 첫 줄은 답이어야 한다 — 이 말로 시작하면 답이 한 줄 밀린다. */
const PREAMBLES = [
  "확인해 보니", "확인해보니", "정리하면", "정리해 드리면", "상황을 말씀드리면",
  "말씀드리면", "결론부터", "우선", "먼저 말씀", "네, ", "넵, ", "알겠습니다.",
];

/** 아부. 만든 사람에게 가장 쓸모없는 답이 "좋은 생각이십니다" 다. */
const FLATTERY = ["좋은 생각", "훌륭", "역시 사장님", "대단하십니다", "멋진 아이디어", "탁월"];

/**
 * 회사 안에서 쓰는 말. 사람에게 새면 안 된다(09-18 사장님: "유니티가 잰다 그런 거").
 * 낱글자 '자' 는 흔해서 **실제로 나타나는 꼴**만 센다 — 정규식으로 긁으면 '자리·혼자' 가 걸린다.
 */
const INTERNAL_WORDS = [
  "심판자", "기계 판정", "합격 기준", "판정식", "자를 돌렸", "자가 잡았",
  "판을 돌렸", "판이 돌", "회차", "조각 고침", "못 잼",
];

/** 얼버무림. 모르면 모른다고 해야 쓸모가 있다. */
const HEDGES = ["아마도", "아마 ", "~것 같습니다", "인 것 같습니다", "로 보입니다", "추정됩니다"];

export type VoiceVerdict = {
  id: string;
  /** 맞음 · 어긋남 · 못 잼(null). 못 잰 것을 어긋남으로 적지 않는다. */
  ok: boolean | null;
  /** 잰 값. 숫자 없이 적으면 고칠 데가 안 보인다. */
  got: string;
};

export type VoiceOptions = {
  /** 소유자와 말하는 중인가 — 호칭을 센다. */
  owner?: boolean;
  /** 진짜 막혀서 하나 되묻는 턴인가 — 그때만 물음표로 끝낼 수 있다. */
  blocked?: boolean;
  /** 잡담인가 — 잡담은 두 줄까지다. */
  smalltalk?: boolean;
};

/** 빈 줄을 뺀 줄. */
function lines(text: string): string[] {
  return text.split("\n").map((l) => l.trim()).filter(Boolean);
}

/**
 * 첫 **문장**. 처음엔 첫 **줄**을 쟀는데 그게 틀렸다(10-26 실측).
 *
 * "모르겠습니다. 장부를 아직 못 읽었습니다. 회사 쪽 문이 막혀 있어서…" 는 50자 한 줄인데
 * **첫 문장은 7자**다 — 답이 맨 앞에 있다. 그런데 자는 줄 길이를 보고 떨어뜨렸다.
 * 재려던 것은 "답이 먼저 오나" 였고 줄 길이는 그 **대리 지표**였다([[measure-the-thing-not-a-proxy]]).
 * 정규식을 안 쓴다 — 백슬래시가 접히는 자리에서 조용히 틀린 값이 나온다(09-27).
 */
function firstSentence(line: string): string {
  const 끝표 = ["다.", "요.", "다!", "요!", "다?", "요?", "?", "!", ". "];
  let 자리 = -1;
  for (const t of 끝표) {
    const i = line.indexOf(t);
    if (i >= 0 && (자리 < 0 || i < 자리)) 자리 = i + t.trimEnd().length;
  }
  return 자리 > 0 ? line.slice(0, 자리) : line;
}

/** 사장님 손이 필요하다고 적은 줄. 명령형 꼬리로 가린다. */
function askLines(ls: string[]): string[] {
  const 꼬리 = ["하세요", "해 주세요", "해주세요", "누르세요", "붙이세요", "돌리세요", "넣으세요", "주시면"];
  return ls.filter((l) => 꼬리.some((k) => l.includes(k)));
}

/**
 * 말투를 센다. **모델이 모델을 채점하지 않는다** — 09-16 에 확인한 대로
 * 화면 보는 AI 를 문으로 쓰면 애매할 때 통과 쪽으로 기운다. 여기선 전부 기계가 센다.
 */
export function checkVoice(text: string, opts: VoiceOptions = {}): VoiceVerdict[] {
  const ls = lines(text);
  const 첫줄 = ls[0] ?? "";
  const out: VoiceVerdict[] = [];
  const 적기 = (id: string, ok: boolean | null, got: string) => out.push({ id, ok, got });

  if (!ls.length) {
    적기("빈 답", false, "줄 0개");
    return out;
  }

  /* ① 첫 줄이 답이다 — 머리말로 시작하지 않고, 짧다. */
  const 머리말 = PREAMBLES.find((p) => 첫줄.startsWith(p));
  적기("첫 줄이 머리말이 아니다", !머리말, 머리말 ? `"${머리말}" 로 시작` : `"${첫줄.slice(0, 20)}…"`);
  /* **첫 문장**을 센다 — 줄 길이는 대리 지표였고 멀쩡한 답을 떨어뜨렸다. */
  const 첫문장 = firstSentence(첫줄);
  적기("첫 문장이 45자 이하", 첫문장.length <= 45, `${첫문장.length}자 "${첫문장.slice(0, 24)}"`);

  /* ② 길이. 잡담은 더 짧다. */
  const 한도 = opts.smalltalk ? 2 : 6;
  적기(`${한도}줄 이하`, ls.length <= 한도, `${ls.length}줄`);

  /* ③ 호칭. **매 줄 "사장님" 을 요구하지 않는다** — 처음엔 그렇게 적었는데 예시 여섯 중
     다섯이 떨어졌다. 사람은 한 마디마다 상대를 부르지 않는다. 그건 자가 틀린 것이다.
     그래서 어긋난 호칭만 센다. */
  const 딴호칭 = ["당신", "고객님", "사용자님", "유저님"].filter((w) => text.includes(w));
  적기("어긋난 호칭 0개", 딴호칭.length === 0, 딴호칭.length ? 딴호칭.join("·") : "0개");

  /* ④ 안쪽 낱말이 새지 않는다. */
  const 샌것 = INTERNAL_WORDS.filter((w) => text.includes(w));
  적기("안쪽 낱말 0개", 샌것.length === 0, 샌것.length ? 샌것.join("·") : "0개");

  /* ⑤ 아부 0개. */
  const 아부 = FLATTERY.filter((w) => text.includes(w));
  적기("아부 0개", 아부.length === 0, 아부.length ? 아부.join("·") : "0개");

  /* ⑥ 얼버무리지 않는다. */
  const 얼 = HEDGES.filter((w) => text.includes(w));
  적기("얼버무림 0개", 얼.length === 0, 얼.length ? 얼.join("·") : "0개");

  /* ⑦ 되묻기로 **턴을 끝내지** 않는다 — 답을 안 주고 묻는 것이 문제다.
     막힌 턴은 예외이고, **잡담도 예외다**: "그 친구가 뭐 했어요?" 로 받는 건 좋은 말이다.
     처음엔 이걸 안 갈라서 멀쩡한 예시가 떨어졌다. */
  const 끝줄 = ls[ls.length - 1] ?? "";
  const 끝이물음 = 끝줄.endsWith("?") || 끝줄.endsWith("？");
  if (opts.blocked) 적기("되묻기", null, "막힌 턴이라 안 센다");
  else if (opts.smalltalk) 적기("되묻기", null, "잡담이라 안 센다");
  else 적기("물음표로 끝내지 않는다", !끝이물음, 끝이물음 ? "물음표로 끝남" : "아니다");

  /* ⑧ 사장님 손이 필요한 것은 **마지막에 모아서, 셋까지.** 비서의 핵심 칸이다. */
  const 부탁 = askLines(ls);
  if (부탁.length === 0) 적기("부탁 자리", null, "부탁이 없다");
  else {
    적기("부탁은 셋까지", 부탁.length <= 3, `${부탁.length}개`);
    const 마지막자리 = ls.slice(-Math.max(3, 부탁.length));
    const 모여있나 = 부탁.every((l) => 마지막자리.includes(l));
    적기("부탁은 뒤에 모여 있다", 모여있나, 모여있나 ? "뒤에 있다" : "중간에 섞여 있다");
  }

  /* ⑨ '아는 것/모르는 것' 목록을 만들지 않는다. */
  const 목록 = text.includes("아는 것") && text.includes("모르는 것");
  적기("아는것/모르는것 목록 없음", !목록, 목록 ? "있다" : "없다");

  return out;
}

/** 통과·어긋남·못 잼을 센다. */
export function voiceScore(vs: VoiceVerdict[]): { pass: number; fail: number; unknown: number; failed: string[] } {
  return {
    pass: vs.filter((v) => v.ok === true).length,
    fail: vs.filter((v) => v.ok === false).length,
    unknown: vs.filter((v) => v.ok === null).length,
    failed: vs.filter((v) => v.ok === false).map((v) => `${v.id} (${v.got})`),
  };
}

