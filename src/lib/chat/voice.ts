/** 비서 말투를 시스템 지시에 붙인다. 예시까지 같이 붙는다. */
export function secretaryNote(): string {
  const 예 = SECRETARY_EXAMPLES
    .map((e) => `사람: ${e.물음}\n너: ${e.답}`)
    .join("\n\n");
  return `${SECRETARY_RULES}\n\n이렇게 말한다:\n\n${예}\n`;
}
