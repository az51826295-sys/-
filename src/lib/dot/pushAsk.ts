/**
 * **알림을 켜 달라고 물어볼 때인가** (10-12).
 *
 * 장부로 세 보니 쓴 사람 18명 중 **알림을 켠 사람이 0명**이었다. 장치가 없어서가 아니다 —
 * 방 ⋮ 메뉴 안에 "하루 한 번, 먼저 말을 걸어요" 가 분명히 있었다. **아무도 못 찾은 것이다.**
 * 알림은 이 앱에서 사람을 **돌아오게 만드는 유일한 장치**라, 못 찾으면 그걸로 끝이다.
 *
 * 이 판단을 화면에서 떼어 둔 까닭: 화면은 로그인해야 볼 수 있어 자가 못 돈다.
 * **묻는 때를 틀리는 것**이 이 기능의 진짜 위험이라(이미 켠 사람에게 또 묻기, 거절한 사람에게
 * 또 묻기, 첫 줄부터 들이밀기) 그 판단만은 자가 재지 못하면 안 된다.
 */

/** 화면이 들고 있는 알림 상태. `push-client.ts` 의 PushState 와 같은 말들이다. */
export type 알림상태 = "on" | "off" | "denied" | "unsupported" | null;

export const 물어볼턴 = 4;

export function 물어볼까(안: {
  로그인: boolean;
  알림: 알림상태;
  내가건말: number;
  전에물음: boolean;
  이미띄움: boolean;
}): boolean {
  if (!안.로그인) return false;
  if (안.이미띄움) return false;            // 이미 떠 있으면 또 켜지 않는다
  if (안.전에물음) return false;            // **한 번만** — 거절한 사람에게 또 묻는 건 알림을 끄게 만드는 가장 빠른 길이다
  // 이미 켠 사람 · 못 쓰는 기기 · 브라우저가 막은 사람에게는 묻지 않는다
  if (안.알림 === "on" ||안.알림 === "unsupported" || 안.알림 === "denied") return false;
  if (안.알림 === null) return false;       // 아직 모르는 상태에서 묻지 않는다
  // 처음부터 들이밀지 않는다 — 몇 마디 나눠 본 뒤에야 "또 이야기하고 싶다" 가 말이 된다
  return 안.내가건말 >= 물어볼턴;
}
