/* ───────────── 어디에 적나 — 새 표 없이 ─────────────
 *
 * 이 기계에는 DDL 열쇠가 없다(관리 토큰·psql·pg 셋 다 없음). 그래서 `dot_tarot` 표를
 * 못 만든다. 대신 **대화 한 줄로 남긴다** — `dot_messages` 의 role 은 'user'·'character'
 * 둘뿐이라 캐릭터가 한 말로 적는다. 좋은 점이 더 있다: 되돌아보면 그때 그 자리에 카드가
 * 그대로 남아 있고, 모델도 자기가 한 말로 읽는다(JSON 을 적으면 모델이 JSON 을 읽는다).
 *
 * 첫 줄이 표시다: `🔮 타로 · 3단계`. 이걸로 **그 단계에서 이미 뽑았는지**를 센다.
 */
export const TAROT_MARK = "🔮 타로 · ";

export const tarotHead = (단계: number) => `${TAROT_MARK}${단계}단계`;

/**
 * 사람이 읽을 수 있고 화면이 되읽을 수 있는 한 덩이로.
 *
 * 받는 꼴을 **여기서 다시 적는다**(`Reading` 을 들고 오지 않는다). 그 타입은 zod 스키마에
 * 붙어 있고 그 파일은 모델 공급자를 끌고 온다 — 이 파일은 브라우저로도 간다.
 */
export function formatReading(
  r: { 뽑기: Draw[]; 카드말: { 자리: string; 한줄: string }[]; 관계: string },
  단계: number,
): string {
  const 줄 = r.뽑기.map((d) => {
    const 말 = r.카드말.find((x) => x.자리 === d.자리)?.한줄 ?? "";
    return `${d.자리} · ${카드이름(d)} — ${말}`;
  });
  return [tarotHead(단계), ...줄, "", r.관계].join("\n");
}

/** 적어 둔 한 덩이를 카드로 되읽는다. 표시가 없으면 null — 보통 대화다. */
export function parseReading(content: string): { 단계: number; 카드: { 자리: string; 카드: Card; 역방향: boolean; 한줄: string }[]; 관계: string } | null {
  if (!content.startsWith(TAROT_MARK)) return null;
  const 줄들 = content.split("\n");
  const 단계 = Number(줄들[0].replace(TAROT_MARK, "").replace("단계", "")) || 0;
  const 카드: { 자리: string; 카드: Card; 역방향: boolean; 한줄: string }[] = [];
  let 관계 = "";
  for (const l of 줄들.slice(1)) {
    const m = l.match(/^(\S+) · (.+?)(\(역방향\))? — (.*)$/);
    if (m && (DECK as readonly string[]).includes(m[2])) {
      카드.push({ 자리: m[1], 카드: m[2] as Card, 역방향: !!m[3], 한줄: m[4] });
    } else if (l.trim()) 관계 += (관계 ? " " : "") + l.trim();
  }
  return 카드.length ? { 단계, 카드, 관계 } : null;
}

