/** 지금 열쇠가 있어 실제로 쓸 수 있는 손만. 없는 것을 있다고 말하지 않는다. */
export function 쓸수있는손(): Mesh3dHand[] {
  return MESH3D.filter((h) => {
    const v = process.env[h.열쇠]?.trim();
    if (!v) return false;
    // fal 손은 모델 id 를 아직 안 채웠으면 못 쓴다 — 키가 있어도 부를 대상이 없다.
    if (h.문 === "fal" && !h.모델) return false;
    return true;
  });
}

/** 사람이 읽는 한 줄. "무엇이 있고 무엇이 없나" 를 대화가 그대로 말할 수 있게. */
export function 손현황(): string {
  const 줄 = MESH3D.map((h) => {
    const 열쇠있음 = !!process.env[h.열쇠]?.trim();
    const 준비 = 열쇠있음 && (h.문 !== "fal" || !!h.모델);
    return `- ${h.이름}: ${준비 ? "쓸 수 있다" : 열쇠있음 ? "열쇠는 있는데 모델 id 가 비었다" : `열쇠 없음(${h.열쇠})`}` +
      (h.잰값?.초 ? ` · 우리가 잰 것 ${h.잰값.초}초` : h.들은값 ? ` · 들은 것: ${h.들은값}` : "");
  });
  return ["## 3D 손", ...줄, "", "**들은 것과 잰 것은 다르다.** 들은 것으로 도구를 고르지 않는다."].join("\n");
}
