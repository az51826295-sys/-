import { LANGUAGE_FOR_MODEL, type Locale } from "./core";

/**
 * 10-14 "전세계화": 모델에게 **사람의 언어로 답하라**고 붙이는 한 토막(로키 대화·화면 보기·이거처럼).
 *
 * 지시문과 예시가 전부 한국어라 이 줄 없이 영어로 물으면 한국어로 답이 온다. 그래서 시스템 맨 **뒤에** 붙인다.
 * 한국어 사용자에게는 아무것도 안 붙는다(프롬프트·캐시가 예전과 같다).
 * JSON 키·정해진 값(enum)은 코드가 읽는 것이라 바꾸지 말라고 같이 적는다 — 번역하면 화면이 못 읽는다.
 */
export function replyLanguageNote(locale: Locale): string {
  if (locale === "ko") return "";
  const lang = LANGUAGE_FOR_MODEL[locale];
  return [
    "",
    "",
    "## 언어 — 가장 중요 (위 규칙보다 앞선다)",
    `이 사람은 **${lang}** 를 쓴다. 사람에게 보이는 글(답·설명·목록·되묻기)은 전부 자연스러운 ${lang} 로 쓴다.`,
    "위 지시문과 예시 말은 한국어지만 **뜻만** 따르고, 말은 이 언어로 옮겨 쓴다. 한국어를 섞지 않는다.",
    "단, 사람이 이번에 다른 언어로 말을 걸었으면 그 언어로 답한다.",
    "JSON 의 키 이름과 정해진 값(목록에서 고르는 값·id)은 그대로 둔다 — 코드가 읽는다.",
  ].join("\n");
}
