/**
 * **주문 한 줄 → 그 장르에서 당연한 것** (228회차 10-02, 사장님 지시).
 *
 * 사장님: *"사용자가 횡스크롤을 만들겠다 하면 다른 게임을 참고하라는 거지."*
 *
 * ## 무엇이 문제였나
 * "횡스크롤 게임 만들어 줘" 는 **주문이 아니라 장르 이름**이다. 지금까지는 그 빈칸을 내가 메웠고,
 * 내가 메우면 **그 장르에서 당연한 것을 빠뜨린다** — 횡스크롤인데 코요테 타임이 없고, 대시가 없고,
 * 맞았을 때 멈칫(히트스톱)이 없다. 그런 게임은 "돌아가지만 재미없다" 로 끝난다.
 * 사람이 그걸 잡아내려면 그 장르를 많이 해 봐야 하는데, **모델은 많이 봤다.** 그걸 쓰자는 것이다.
 *
 * ## 참고는 '사실 확인' 이 아니라 '빠뜨림 막기' 다
 * 모델이 "스컬에는 머리 교체가 있다" 를 틀리게 적을 수도 있다. 그래도 **쓸모는 남는다** —
 * 우리가 쓰려는 것은 그 게임의 족보가 아니라 **그 장르에서 사람들이 기대하는 것**이기 때문이다.
 * 그래서 `확실한가` 를 따로 받아 적고, **기준 문장 자체는 우리 게임에서 확인할 수 있는 것**만 쓴다.
 * (틀린 족보로 기준을 세워도 기준이 우리 화면에서 참거짓이 갈리면 해는 없다. 그 선을 넘지 않게 한다.)
 *
 * ## 그림과 이름은 안 가져온다
 * 참고는 **구조와 손맛**까지다. 캐릭터·도트·음악·이름은 그 회사 것이다.
 */
import { z } from "zod";

export const 참고게임꼴 = z.object({
  장르: z.string().describe("주문을 읽고 가린 장르. 한 줄."),
  참고작: z.array(z.object({
    이름: z.string(),
    왜: z.string().describe("이 장르에서 왜 잘 됐다고 보는가 — 한 줄"),
    배울것: z.array(z.string()).describe("그 게임이 이 장르에서 지킨 것 1~3개"),
    확실한가: z.enum(["확실", "아마", "모름"]).describe("네가 적은 내용이 그 게임에 실제로 있는지"),
  })).describe("2~4개."),
  당연한것: z.array(z.string()).describe("이 장르라면 **없으면 이상한 것**. 사람들이 말 안 해도 기대하는 것."),
  기준: z.array(z.object({
    id: z.string().describe("G01 처럼"),
    when: z.string().describe("무엇을 하면"),
    then: z.string().describe("무엇이 보이는가 — **우리 게임에서** 눌러 보고 참거짓을 가릴 수 있게"),
    왜: z.string().describe("이게 왜 이 장르에 필요한가 — 한 줄"),
  })).describe("8~16개. 이것이 주문에 더해진다."),
  안가져올것: z.array(z.string()).describe("참고작 고유의 것(이름·캐릭터·그림·음악·이야기)."),
  사람이정할것: z.array(z.string()).describe("장르만으로는 못 정하는 것 — 사장님이 골라야 하는 자리."),
});

