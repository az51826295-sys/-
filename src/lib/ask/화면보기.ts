/** 길과 자가 같은 말을 묻게 — 이 글이 목(mock)의 갈림길 표시이기도 하다("지금 말을 걸 만한가"). */
export function 화면물음(앞말?: string[], 마지막말?: string): string {
  return [
    "화면 한 장이다. 지금 말을 걸 만한가?",
    앞말?.length ? `\n## 조금 전 대화\n${앞말.slice(-4).join("\n")}` : "",
    마지막말 ? `\n## 내가 마지막으로 한 말\n${마지막말}\n같은 말을 또 하지 마라.` : "",
  ].filter(Boolean).join("\n");
}
