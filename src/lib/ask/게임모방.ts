/**
 * **게임 화면 여러 장 → 만들 수 있는 기준** (228회차 10-02, 사장님 "게임 모방").
 *
 * UI 모방(`모방.ts`)은 **한 장**으로 된다. 배치는 멈춰 있어도 보이기 때문이다.
 * 게임은 안 된다 — **움직임과 규칙이 알맹이**인데 그건 한 장에 안 담긴다.
 * 그래서 여기는 **여러 장**(시간 차가 있는 장면)을 받는다. 장면 사이가 달라진 것이 곧 규칙의 흔적이다.
 *
 * ## 나오는 것이 '감상문' 이면 쓸모가 없다
 * "재미있고 빠른 슈팅 게임" 같은 말로는 아무것도 못 만든다. 그래서 마지막에 **기준 목록**을 뽑게 한다 —
 * `app_build` 가 쓰는 것과 **같은 모양**(`id · when · then`)이라 그대로 주문이 된다.
 * 기준은 **사람이 눌러 보고 참거짓을 가릴 수 있는 문장**이어야 한다(09-xx C2: '빠르다' 가 아니라 '50개에서도 부드럽다').
 *
 * ## 베끼지 않는 것
 * 캐릭터·이름·그림·소리·이야기는 **그 게임 것**이다. 우리가 배우는 것은 **구조와 손맛**이다.
 * 이걸 안 적으면 나중에 남의 캐릭터를 그대로 만들어 놓고 모방했다고 말하게 된다.
 */
import { z } from "zod";

export const 게임모방꼴 = z.object({
  무엇: z.string().describe("무슨 게임인지 한 줄. 장르와 시점(2D/3D, 위에서/옆에서/1인칭)."),
  화면칸: z.array(z.string()).describe("화면에 늘 떠 있는 것들(점수·체력·시간·지도 등)과 그 자리."),
  조작: z.string().describe("보이는 것으로 짐작되는 조작. 모르면 '장면으로는 모른다'."),
  규칙: z.array(z.string()).describe("장면 사이의 **차이**로 알 수 있는 규칙만. 예: '적이 맞으면 사라지고 점수가 10 오른다'."),
  손맛: z.string().describe("빠른가 느린가, 무거운가 가벼운가, 반응이 즉각적인가. 왜 그렇게 봤는지 한 마디."),
  그림결: z.string().describe("도트/벡터/3D, 색 수, 외곽선 유무 등 **따라 만들 수 있는 말**로."),
  기준: z.array(z.object({
    id: z.string().describe("C01 처럼"),
    when: z.string().describe("무엇을 하면"),
    then: z.string().describe("무엇이 보이는가 — 사람이 눌러 보고 참거짓을 가릴 수 있게"),
  })).describe("10~18개. 이것이 그대로 주문이 된다."),
  안가져올것: z.array(z.string()).describe("그 게임 고유의 것(캐릭터·이름·그림·소리·이야기)."),
  못본것: z.array(z.string()).describe("장면으로는 알 수 없는 것. **반드시 채운다.**"),
});

