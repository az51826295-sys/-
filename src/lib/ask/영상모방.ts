/**
 * **영상 여러 장 → 만들 수 있는 컷 표** (228회차 10-02, 사장님 "영상 하나랑 게임 하나로 가자").
 *
 * 게임 모방(`게임모방.ts`)과 닮았지만 재는 것이 다르다. 게임은 **규칙**이 알맹이고,
 * 영상은 **시간**이 알맹이다 — 무엇이 몇 초에 나오고 얼마나 머무는가.
 * 그래서 장면마다 **몇 초 지점에서 떴는지**를 같이 준다. 그게 없으면 "좋은 영상" 같은 말밖에 안 나온다.
 *
 * ## 우리가 이미 아는 것
 * 09-17 에 말 속도를 상수로 박아 두었다가 20초 주문이 15.7초로 나온 일이 있다([[speech-rate-is-measured]]).
 * 그래서 여기서도 **초를 지어내게 두지 않는다** — 장면에 붙은 초를 보고 적게 한다.
 *
 * ## 못 보는 것
 * 소리·음악·말소리는 장면에 없다. 컷 사이 전환도 한 장씩 떠서는 흐릿하다. 그건 `못본것` 이다.
 */
import { z } from "zod";

export const 영상모방꼴 = z.object({
  무엇: z.string().describe("무슨 영상인지 한 줄. 무엇을 파는/알리는 영상인가."),
  컷표: z.array(z.object({
    초: z.string().describe("몇 초 지점인지(준 장면의 초를 그대로)"),
    무엇: z.string().describe("그 장면에 무엇이 보이는가"),
    글자: z.string().describe("화면에 적힌 글자. 없으면 '없음'"),
  })).describe("준 장면 수만큼."),
  길이: z.string().describe("전체 몇 초인가, 컷이 몇 개로 보이는가."),
  글자쓰임: z.string().describe("글자가 언제 나오고 어디에 놓이는가. 소리를 꺼도 읽히는가."),
  리듬: z.string().describe("컷이 빠른가 느린가, 어디서 머무는가. 왜 그렇게 봤는지."),
  기준: z.array(z.object({
    id: z.string().describe("V01 처럼"),
    무엇: z.string().describe("만들 때 지켜야 할 것 — 숫자가 들어가야 한다"),
  })).describe("8~14개. 이것이 그대로 영상 주문이 된다."),
  안가져올것: z.array(z.string()).describe("그 영상 고유의 것(상표·캐릭터·음악·문구)."),
  못본것: z.array(z.string()).describe("장면으로는 알 수 없는 것(소리·말·전환). **반드시 채운다.**"),
});

