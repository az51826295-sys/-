/**
 * **거짓말의 온도 — 진실 데이터베이스** (228회차 10-01, 사장님 기획).
 *
 * 사장님 기획의 ① 번: *"AI 가 거짓말을 하더라도 사건의 불변하는 진실을 기억하고 있어야 합니다."*
 *
 * ## 이 파일이 지키는 한 가지
 * **진실은 여기 있고, 용의자는 자기 몫만 안다.** 세 사람에게 같은 프롬프트를 주면
 * 서로의 비밀까지 알게 되고, 그러면 한 명만 깨도 나머지가 줄줄이 샌다.
 * 그래서 `프롬프트조각()` 이 용의자마다 **자기가 아는 것만** 잘라 준다.
 *
 * ## 왜 데이터로 두나
 * 진실을 모델이 "기억" 하게 두면 회차마다 사건이 달라진다(09-30 에 같은 주문으로 7판을 돌려 보니
 * 판마다 다른 게임이 나왔다). 사건은 **고정된 표**여야 하고, 모델이 지어내는 것은 **그 표를 숨기는 말**뿐이다.
 *
 * 등장인물·사건은 **사장님이 적은 그대로**다. 내가 지어낸 것이 아니다.
 */

/** 플레이어가 들이대는 물건. `낱말` 은 플레이어 말에서 이 증거를 가리키는 말이다. */
export type 증거 = {
  id: string;
  이름: string;
  /** 플레이어가 보는 설명. */
  설명: string;
  /** 이 중 하나라도 플레이어 말에 있으면 "이 증거를 들이댔다" 로 센다. */
  낱말: string[];
};

/** 증거 하나가 어떤 진술을 깨는가. **이것이 모순 감지 엔진의 표다.** */
export type 약점 = {
  증거id: string;
  /** 이 증거가 깨뜨리는 거짓 진술. */
  깨지는진술: string;
  /** 깨졌을 때 당황이 얼마나 오르나(0~100 중). */
  당황: number;
  /** 깨진 뒤 용의자가 내놓는 **다음 거짓말**(아직 자백은 아니다). */
  둘러대기: string;
};

export type 용의자 = {
  id: string;
  이름: string;
  관계: string;
  /** 플레이어 눈에 보이는 겉모습·태도. */
  겉모습: string;
  /** 말투 지침 — 숫자로 적을 수 없는 것은 여기 둔다. */
  말투: string;
  /** **진짜 범인인가.** 무고한 사람은 아무리 몰아붙여도 살인을 자백하지 않는다. */
  범인: boolean;
  /** 이 사람이 실제로 한 일(진실). 플레이어에게 절대 먼저 나가면 안 된다. */
  진실: string;
  /** 이 사람이 숨기는 것 — 범인이 아니어도 누구나 숨기는 게 있다. */
  숨긴것: string;
  /** 처음에 내놓는 거짓 알리바이. */
  거짓알리바이: string;
  약점: 약점[];
  /** 멘탈이 깨졌을 때 **실토하는 것**. 범인이면 자백, 아니면 숨긴 것. */
  무너지면: string;
};

/**
 * **교차 검증** — 한 용의자의 말이 다른 용의자에게 가서 깨진다.
 *
 * 이게 추리 게임의 알맹이다. 증거는 형사가 **가지고 들어오는** 것이지만, 증언은 **취조로 만들어 내는** 것이다.
 * A 가 *"윤미래 씨와 카페에 있었다"* 고 했으면, 윤미래에게 가서 물어야 한다.
 * 윤미래가 *"한선호 씨요? 그날 저는 집에 있었는데요"* 라고 하면 — 그 말이 **새 증거**가 되어 A 를 깬다.
 *
 * 그래서 이 표는 **세 곳을 잇는다**: 누가 한 주장 · 누구에게 물어야 하나 · 그 답이 무슨 증거가 되나.
 */
export type 교차 = {
  id: string;
  /** 이 주장을 한 용의자. */
  주장한사람: string;
  /** 플레이어 눈에 보이는 주장 한 줄(화면의 '확인할 것' 목록에 쓴다). */
  주장: string;
  /** 이걸 확인하려면 누구에게 물어야 하나. */
  물을사람: string;
  /** 그 사람에게 **이 낱말들로 물으면** 확인된 것으로 센다. */
  낱말: string[];
  /** 물었을 때 그 사람이 내놓는 반박. 이 말이 곧 증언이다. */
  반박: string;
  /** 이 확인으로 **새로 생기는 증거**. 플레이어의 증거 목록에 더해진다. */
  생기는증거: 증거;
  /** 그 증거가 주장한 사람의 무엇을 깨나. */
  깨는약점: 약점;
};

export type 사건 = {
  id: string;
  제목: string;
  피해자: string;
  발생시각: string;
  장소: string;
  /** 플레이어는 모르는 진실 전체. 용의자 프롬프트에 **통째로 넣지 않는다.** */
  진실: string;
  증거: 증거[];
  용의자: 용의자[];
  교차: 교차[];
  /** **범인이 누구인가.** 최종 지목을 채점하는 데만 쓴다. */
  범인id: string;
  /** 지목이 맞으려면 **이 증거들을 손에 넣었어야** 한다. 찍어서 맞히는 것을 막는다. */
  지목에필요한증거: string[];
};

