/** 이 용의자를 깨는 약점 전부 — 표에 적힌 것 + **교차 검증으로 얻은 증언**. */
export function 약점전부(사건: 사건, 용의자: 용의자, 얻은증언: string[] = []): 약점[] {
  const 증언약점 = 사건.교차
    .filter((x) => x.주장한사람 === 용의자.id && 얻은증언.includes(x.생기는증거.id))
    .map((x) => x.깨는약점);
  return [...용의자.약점, ...증언약점];
}

/** 플레이어가 지금 손에 쥔 증거 — 처음부터 있던 것 + 얻은 증언. */
export function 가진증거(사건: 사건, 얻은증언: string[] = []): 증거[] {
  const 증언 = 사건.교차.filter((x) => 얻은증언.includes(x.생기는증거.id)).map((x) => x.생기는증거);
  return [...사건.증거, ...증언];
}

/**
 * **용의자마다 자기 몫만 잘라 준다.** 사건 전체 진실은 안 넣는다 —
 * 넣으면 한 명을 깨뜨렸을 때 나머지 둘의 비밀까지 같이 샌다.
 */
export function 아는것(사건: 사건, 용의자: 용의자): string {
  return [
    `## 사건 (네가 아는 만큼)`,
    `- 피해자: ${사건.피해자}`,
    `- 죽은 시각: ${사건.발생시각}`,
    `- 장소: ${사건.장소}`,
    `- 너와 피해자의 관계: ${용의자.관계}`,
    ``,
    `## 너만 아는 것 (**절대 먼저 말하지 마라**)`,
    `- 네가 실제로 한 일: ${용의자.진실}`,
    `- 네가 숨기는 것: ${용의자.숨긴것}`,
    `- 네가 내놓는 알리바이(거짓): ${용의자.거짓알리바이}`,
  ].join("\n");
}

export const 용의자찾기 = (사건: 사건, id: string) => 사건.용의자.find((s) => s.id === id) ?? null;
export const 증거찾기 = (사건: 사건, id: string) => 사건.증거.find((e) => e.id === id) ?? null;
