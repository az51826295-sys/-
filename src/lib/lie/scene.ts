/**
 * **거짓말의 온도 — 현장 조사** (228회차 10-01, 사장님 기획 1단계).
 *
 * *"사건 현장 조사와 피해자 부검 소견을 통해 기본 증거물을 확보하고 심문실에 들어갑니다."*
 *
 * ## 왜 이걸 붙이나
 * 10-01 까지는 증거 6개가 **처음부터 다 손에 있었다.** 그러면 취조가 "다 들이대 보기" 가 된다.
 * 찾아낸 증거여야 들이댈 때 무게가 생기고, **내가 무엇을 모르는지**를 알게 된다.
 *
 * ## 셈만 한다 — 모델 0
 * 여기엔 AI 가 없다. 어디를 보면 무엇이 나오는지는 **표**이고, 표를 읽는 것은 셈이다.
 * (모델에게 맡기면 같은 서랍에서 회차마다 다른 게 나온다 — 그건 조사가 아니라 뽑기다.)
 *
 * ## 답은 서버에만
 * `보면` 글과 `얻는증거` 는 화면으로 안 내려간다. 내려가면 개발자 도구로 다 읽힌다.
 * 화면이 받는 것은 **지점 이름과 잠겼는지**뿐이다.
 */
import type { 사건, 조사지점 } from "./case";

/** `필요한증거` 의 특별한 꼴: `__지점id__` 는 "그 **지점을 조사했는가**" 를 뜻한다. */
const 지점조건 = (s: string | undefined) => (s?.startsWith("__") && s.endsWith("__") ? s.slice(2, -2) : null);

export function 열렸나(지점: 조사지점, 본지점: string[], 가진증거: string[]): boolean {
  if (!지점.필요한증거) return true;
  const 필요한지점 = 지점조건(지점.필요한증거);
  return 필요한지점 ? 본지점.includes(필요한지점) : 가진증거.includes(지점.필요한증거);
}

export type 현장상태 = { 본지점: string[]; 가진증거: string[] };

export const 현장처음 = (사건: 사건): 현장상태 => ({ 본지점: [], 가진증거: [...사건.시작증거] });

export type 조사결과 =
  | { 됨: false; 까닭: string }
  | { 됨: true; 글: string; 얻은증거: { id: string; 이름: string; 설명: string } | null; 상태: 현장상태; 이미봄: boolean };

export function 조사하기(사건: 사건, 앞: 현장상태, 지점id: string): 조사결과 {
  const 지점 = 사건.현장.지점.find((p) => p.id === 지점id);
  if (!지점) return { 됨: false, 까닭: "그런 자리는 없다" };
  if (!열렸나(지점, 앞.본지점, 앞.가진증거)) return { 됨: false, 까닭: 지점.잠긴말 ?? "아직 여기를 볼 까닭이 없다" };

  // 같은 곳을 또 봐도 같은 글이 나온다. **두 번째에 새 증거는 안 준다.**
  const 이미봄 = 앞.본지점.includes(지점id);
  const 상태: 현장상태 = { 본지점: [...앞.본지점], 가진증거: [...앞.가진증거] };
  if (!이미봄) 상태.본지점.push(지점id);

  let 얻은증거: 조사결과 extends never ? never : { id: string; 이름: string; 설명: string } | null = null;
  if (지점.얻는증거 && !상태.가진증거.includes(지점.얻는증거)) {
    const e = 사건.증거.find((x) => x.id === 지점.얻는증거);
    if (e) { 상태.가진증거.push(e.id); 얻은증거 = { id: e.id, 이름: e.이름, 설명: e.설명 }; }
  }
  return { 됨: true, 글: 지점.보면, 얻은증거, 상태, 이미봄 };
}

/** 화면에 내려보낼 **안전한** 지점 목록 — 답은 빼고 이름과 잠김만. */
export function 보여줄지점(사건: 사건, 상태: 현장상태) {
  return 사건.현장.지점.map((p) => ({
    id: p.id, 곳: p.곳, 이름: p.이름,
    봤나: 상태.본지점.includes(p.id),
    잠김: !열렸나(p, 상태.본지점, 상태.가진증거),
  }));
}

/**
 * **취조실에 들어갈 수 있나.** 아무것도 안 찾고 들어가면 할 수 있는 게 없다.
 * 다만 **다 찾아야** 들어갈 수 있게 하면 조사가 숙제가 된다 — 둘(시작증거 포함 셋)이면 연다.
 */
export const 들어갈수있나 = (상태: 현장상태) => 상태.가진증거.length >= 3;
