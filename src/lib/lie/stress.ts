/**
 * **거짓말의 온도 — 수치 시스템과 모순 감지** (228회차 10-01, 사장님 기획 ②③).
 *
 * ## 모델에게 묻지 않는다
 * 압박이 얼마나 올랐는지를 모델이 정하면 **회차마다 다른 게임**이 된다. 같은 증거를 들이대도
 * 어떤 판은 무너지고 어떤 판은 안 무너지면 그건 추리가 아니라 운이다.
 * 그래서 여기 있는 것은 전부 **셈**이다. 모델이 하는 일은 *"이 수치에 맞는 사람처럼 말하기"* 하나뿐이다.
 * (두근도트 친밀도에서 같은 구조가 먹혔다 — 점수는 규칙이 세고 모델은 말투만 바꾼다.)
 *
 * ## 네 가지 수치 (0~100)
 *  - **압박**: 몰린 정도. 이것이 임계를 넘고 약점이 충분히 깨지면 **멘탈 브레이크**.
 *  - **당황**: 방금 한 방 맞았나. 빨리 오르고 빨리 식는다 — 말문이 막히는 건 이쪽이다.
 *  - **분노**: 함부로 다루면 오른다. 높으면 입을 닫는다(압박만 올린다고 다 불지 않는다).
 *  - **경계**: 떠보는 걸 눈치챘나. 높으면 짧게 답하고 증거의 효과가 깎인다.
 *
 * ## 왜 분노와 경계가 따로 있나
 * 압박 하나만 두면 **아무 말이나 세게 하면 이기는 게임**이 된다. 그건 취조가 아니다.
 * 몰아붙이기만 하면 분노가 올라 입을 닫고, 같은 걸 자꾸 물으면 경계가 올라 증거가 덜 먹힌다.
 * 라포(부드러운 질문)로 분노·경계를 내려 두고 결정적인 증거를 꽂는 것이 제일 빠른 길이 되게 맞췄다.
 */
import { 약점전부, 가진증거, type 사건, type 용의자, type 약점, type 교차 } from "./case";

export type 수치 = { 압박: number; 당황: number; 분노: number; 경계: number };
export type 심문상태 = {
  수치: 수치;
  /** 이미 깨진 약점의 증거 id. 같은 증거를 두 번 들이대도 다시 안 터진다. */
  깨진약점: string[];
  /** 이미 들이댄 증거 전부(안 맞은 것 포함). */
  내민증거: string[];
  /** 지금까지 주고받은 턴 수. */
  턴: number;
  /** 최근 질문들(같은 질문 반복을 잡으려고). 길이 6까지. */
  최근질문: string[];
  /** **무너졌나.** 한 번 참이 되면 되돌리지 않는다. */
  무너짐: boolean;
  /**
   * **교차 검증으로 얻은 증언의 증거 id.** 용의자 방마다가 아니라 **사건 전체**로 들고 다닌다 —
   * 윤미래에게서 얻은 증언을 한선호에게 가서 들이대는 것이 이 게임이다.
   */
  얻은증언?: string[];
};

export const 처음상태 = (): 심문상태 => ({
  수치: { 압박: 10, 당황: 0, 분노: 0, 경계: 15 },
  깨진약점: [], 내민증거: [], 턴: 0, 최근질문: [], 무너짐: false, 얻은증언: [],
});

/** 멘탈 브레이크 문턱. **둘 다** 넘어야 한다 — 압박만으로는 안 된다. */
export const 임계 = { 압박: 80, 깨진약점: 2 } as const;
/** 약점이 하나뿐인 사람(윤미래)은 그 하나로 충분하다. 표에 적힌 것만 센다 — 교차 증언은 **덤**이지 문턱이 아니다. */
export const 필요한약점 = (용의자: 용의자) => Math.min(임계.깨진약점, Math.max(1, 용의자.약점.length));
/**
 * **압박 문턱은 사람마다 다르다.** 약점이 하나뿐인 사람에게 80 을 요구하면 영영 못 닿는다 —
 * 들이댈 증거가 하나뿐이라 압박을 올릴 길이 없다(10-01 셈자 ⑥ 에서 40 에서 멈췄다).
 * 그래서 약점 수에 맞춘다: 1개면 60 · 2개면 80.
 */
export const 문턱압박 = (용의자: 용의자) => 35 + 20 * 필요한약점(용의자);

const 가둠 = (n: number) => Math.max(0, Math.min(100, Math.round(n)));

/** 추궁하는 말. 있으면 압박이 크게 오르고 분노도 오른다. */
const 날카로운말 = ["거짓말", "숨기", "왜 안", "말이 안", "모순", "앞뒤가", "솔직", "자백", "범인", "죽였", "살해", "인정하"];
/** 부드러운 말(라포). 분노·경계를 내린다. */
const 부드러운말 = ["힘드셨", "이해합니다", "쉬었다", "괜찮", "고생", "천천히", "물 한", "미안", "죄송", "도와"];

/**
 * 플레이어 말에서 **들이댄 증거**를 찾는다. 낱말이 걸리면 그 증거를 내민 것으로 센다.
 * 얻은 증언도 증거다 — 그래서 `가진증거` 로 센다.
 */
export function 내민증거찾기(사건: 사건, 말: string, 얻은증언: string[] = []): string[] {
  const 소문자 = 말.toLowerCase();
  return 가진증거(사건, 얻은증언).filter((e) => e.낱말.some((w) => 소문자.includes(w.toLowerCase()))).map((e) => e.id);
}

/**
 * **지금 이 사람에게 물어서 확인되는 교차 검증**이 있나.
 * 이미 얻은 것은 또 안 준다. 낱말이 **둘 이상** 걸려야 센다 — 한 낱말로는 스치듯 지나가도 걸린다.
 */
export function 교차확인(사건: 사건, 용의자: 용의자, 말: string, 얻은증언: string[] = []): 교차 | null {
  const 소문자 = 말.toLowerCase();
  for (const x of 사건.교차) {
    if (x.물을사람 !== 용의자.id) continue;
    if (얻은증언.includes(x.생기는증거.id)) continue;
    const 걸린수 = x.낱말.filter((w) => 소문자.includes(w.toLowerCase())).length;
    if (걸린수 >= 2 || (걸린수 === 1 && x.낱말.length <= 2)) return x;
  }
  return null;
}

/** 같은 질문을 또 하는가 — 낱말이 절반 넘게 겹치면 같은 질문으로 본다. */
function 반복인가(최근: string[], 이번: string): boolean {
  const 낱말 = (s: string) => new Set((s.match(/[가-힣A-Za-z0-9]{2,}/g) ?? []).map((w) => w.toLowerCase()));
  const 이 = 낱말(이번);
  if (이.size < 2) return false;
  return 최근.some((q) => {
    const 저 = 낱말(q);
    if (!저.size) return false;
    let 겹 = 0;
    for (const w of 이) if (저.has(w)) 겹++;
    return 겹 / 이.size >= 0.6;
  });
}

export type 한턴결과 = {
  상태: 심문상태;
  /** 이번에 깨진 약점들(처음 깨진 것만). */
  이번에깨짐: 약점[];
  /** 이번에 내밀었지만 **안 맞은** 증거. 헛다리는 상대를 여유롭게 만든다. */
  헛다리: string[];
  /** 사람이 읽을 수 있는 까닭. 수치가 왜 움직였는지 그대로 적는다. */
  까닭: string[];
  /** 이번 턴에 **처음으로** 무너졌나. */
  방금무너짐: boolean;
  /** 이번 턴에 **새로 얻은 증언**(교차 검증). 있으면 플레이어의 증거가 하나 는다. */
  얻은교차: 교차 | null;
};

/**
 * **한 턴의 셈.** 플레이어 말 + 들이댄 증거 → 수치 갱신.
 * 모델을 부르기 **전에** 다 끝난다 — 모델에게는 결과만 넘긴다.
 */
export function 한턴(사건: 사건, 용의자: 용의자, 앞: 심문상태, 말: string): 한턴결과 {
  const s: 심문상태 = {
    수치: { ...앞.수치 }, 깨진약점: [...앞.깨진약점], 내민증거: [...앞.내민증거],
    턴: 앞.턴 + 1, 최근질문: [...앞.최근질문], 무너짐: 앞.무너짐,
    얻은증언: [...(앞.얻은증언 ?? [])],
  };
  const 까닭: string[] = [];
  const 소문자 = 말.toLowerCase();

  // ── 시간이 지나면 가라앉는다 ────────────────────────────────
  s.수치.압박 = 가둠(s.수치.압박 - 1);
  s.수치.당황 = 가둠(s.수치.당황 * 0.55);          // 당황은 빨리 식는다
  s.수치.분노 = 가둠(s.수치.분노 - 2);

  // ── 말투 ──────────────────────────────────────────────────
  const 날카 = 날카로운말.filter((w) => 소문자.includes(w)).length;
  const 부드 = 부드러운말.filter((w) => 소문자.includes(w)).length;
  if (날카) {
    // **고함은 증거가 아니다.** 압박은 조금만 올리고 **경계를 크게** 올린다 —
    // 소리치면 상대는 말을 맞추고, 그 뒤에 내민 증거가 덜 먹힌다. 이게 라포가 사는 까닭이다.
    s.수치.압박 = 가둠(s.수치.압박 + 2 * Math.min(2, 날카));
    s.수치.분노 = 가둠(s.수치.분노 + 5 * Math.min(2, 날카));
    s.수치.경계 = 가둠(s.수치.경계 + 12);
    까닭.push(`날카로운 말 ${날카}개 — 압박 +${2 * Math.min(2, 날카)} · 분노 +${5 * Math.min(2, 날카)} · **경계 +12**`);
  } else if (부드) {
    s.수치.분노 = 가둠(s.수치.분노 - 10);
    s.수치.경계 = 가둠(s.수치.경계 - 8);
    까닭.push("부드러운 말 — 분노 −10 · 경계 −8");
  } else {
    s.수치.압박 = 가둠(s.수치.압박 + 2);
    s.수치.경계 = 가둠(s.수치.경계 + 1);
  }

  if (반복인가(s.최근질문, 말)) {
    s.수치.분노 = 가둠(s.수치.분노 + 8);
    s.수치.경계 = 가둠(s.수치.경계 + 6);
    까닭.push("같은 걸 또 물었다 — 분노 +8 · 경계 +6");
  }
  s.최근질문 = [...s.최근질문, 말].slice(-6);

  // ── 교차 검증 — 이 사람에게 물어서 **증언을 얻는다** ───────────
  // 증거는 들고 들어오는 것이고, 증언은 **취조로 만들어 내는 것**이다. 이게 이 게임의 알맹이다.
  const 얻은교차 = 교차확인(사건, 용의자, 말, s.얻은증언);
  if (얻은교차) {
    s.얻은증언!.push(얻은교차.생기는증거.id);
    // 남의 이야기를 묻는 것이라 이 사람 자신은 별로 안 몰린다. 경계만 조금 오른다.
    s.수치.경계 = 가둠(s.수치.경계 + 5);
    까닭.push(`**증언을 얻었다** — ${얻은교차.생기는증거.이름}. 이제 ${얻은교차.주장한사람} 에게 들이댈 수 있다.`);
  }

  // ── 증거 ──────────────────────────────────────────────────
  // **이번 턴에 얻은 증언은 이번 턴에 못 내민다.** `앞.얻은증언` 으로 센다 —
  // 안 그러면 윤미래에게 "한선호가 윤미래 씨와 카페에" 라고 묻는 그 말이, 방금 생긴 증언을
  // **윤미래 본인에게 들이댄 것**으로 세어져 헛다리 벌(압박 −5)을 먹는다.
  const 내민것 = 내민증거찾기(사건, 말, 앞.얻은증언 ?? []);
  const 이번에깨짐: 약점[] = [];
  const 헛다리: string[] = [];
  const 이사람약점 = 약점전부(사건, 용의자, s.얻은증언);
  for (const id of 내민것) {
    if (!s.내민증거.includes(id)) s.내민증거.push(id);
    const 약 = 이사람약점.find((w) => w.증거id === id);
    if (!약) {
      // **헛다리.** 안 맞는 증거를 들이대면 상대는 오히려 여유를 얻는다.
      헛다리.push(id);
      s.수치.압박 = 가둠(s.수치.압박 - 5);
      s.수치.경계 = 가둠(s.수치.경계 + 10);
      까닭.push(`안 맞는 증거(${id}) — 압박 −5 · 경계 +10`);
      continue;
    }
    if (s.깨진약점.includes(id)) {
      // 같은 증거를 또 들이대면 처음만큼 안 아프다.
      s.수치.압박 = 가둠(s.수치.압박 + 4);
      까닭.push(`이미 깬 증거(${id})를 또 — 압박 +4`);
      continue;
    }
    // **경계가 높으면 증거가 덜 먹힌다.** 눈치채고 미리 말을 맞춰 둔 것이다.
    const 깎임 = Math.max(0.15, 1 - s.수치.경계 / 120);   // 경계 60 이면 절반만 들어간다
    // **아픈 약점일수록 압박도 크게 오른다.** 30 으로 고정했더니 약점 하나짜리는 문턱에 영영 못 닿았다.
    const 압박올림 = Math.round((30 + 약.당황 / 2) * 깎임);
    const 당황올림 = Math.round(약.당황 * 깎임);
    s.깨진약점.push(id);
    이번에깨짐.push(약);
    s.수치.압박 = 가둠(s.수치.압박 + 압박올림);
    s.수치.당황 = 가둠(s.수치.당황 + 당황올림);
    까닭.push(`**${약.깨지는진술}** 이 깨졌다(${id}) — 압박 +${압박올림} · 당황 +${당황올림}${깎임 < 0.95 ? ` (경계 ${s.수치.경계} 로 ${Math.round((1 - 깎임) * 100)}% 깎임)` : ""}`);
  }

  // ── 분노가 높으면 입을 닫는다 ───────────────────────────────
  if (s.수치.분노 >= 70) 까닭.push(`분노 ${s.수치.분노} — 입을 닫는다(압박이 올라도 안 분다)`);

  // ── 멘탈 브레이크 ─────────────────────────────────────────
  const 문턱 = 문턱압박(용의자);
  const 방금무너짐 = !s.무너짐
    && s.수치.압박 >= 문턱
    && s.깨진약점.length >= 필요한약점(용의자)
    && s.수치.분노 < 70;
  if (방금무너짐) {
    s.무너짐 = true;
    까닭.push(`**무너졌다** — 압박 ${s.수치.압박} ≥ ${문턱} · 깨진 약점 ${s.깨진약점.length}/${필요한약점(용의자)} · 분노 ${s.수치.분노} < 70`);
  }
  return { 상태: s, 이번에깨짐, 헛다리, 까닭, 방금무너짐, 얻은교차 };
}

/** 수치를 **말투 지시**로 바꾼다. 모델에게 숫자를 주면 숫자를 읽어 버린다("압박이 85입니다"). */
export function 태도(s: 심문상태): string {
  const { 압박, 당황, 분노, 경계 } = s.수치;
  const 줄: string[] = [];
  if (당황 >= 50) 줄.push("방금 한 방 맞았다. 말문이 막힌다. 첫 마디를 '어…' '그게…' 처럼 더듬고, 한 문장이 끝까지 안 이어진다.");
  else if (당황 >= 25) 줄.push("살짝 흔들린다. 말이 한 박자 늦고, 같은 말을 한 번 되풀이한다.");

  if (압박 >= 80) 줄.push("몰렸다. 더는 여유가 없다. 문장이 짧아지고 목소리가 떨린다.");
  else if (압박 >= 50) 줄.push("불편하다. 답을 하면서도 상대를 살핀다. 말을 고른다.");
  else if (압박 >= 25) 줄.push("조금 긴장했지만 아직 침착하다.");
  else 줄.push("침착하다. 논리적으로 또박또박 답한다.");

  if (분노 >= 70) 줄.push("화가 많이 났다. **입을 닫는다.** 짧게 끊어 답하고, 되묻거나 변호사 이야기를 꺼낸다. 아는 것을 더 내놓지 않는다.");
  else if (분노 >= 40) 줄.push("기분이 상했다. 말끝이 날카롭고, 한 번쯤 되받아친다.");

  if (경계 >= 60) 줄.push("떠보는 걸 알아챘다. 필요한 말만 짧게 한다. 먼저 덧붙이지 않는다.");
  else if (경계 <= 20) 줄.push("경계가 풀렸다. 묻지 않은 것까지 한두 마디 더 한다.");
  return 줄.join(" ");
}
