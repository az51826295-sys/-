/**
 * **거짓말의 온도 — 한 턴** (228회차 10-01, 사장님 기획).
 *
 * 흐름은 사장님 그림 그대로다:
 *   플레이어 말(+증거) → **시스템 레이어**(모순 검증) → **심리 엔진**(수치) → **용의자 LLM**(대사) → 답
 *
 * ## 이 파일이 지키는 두 가지
 *
 * **① 자백은 코드가 연다.** 프롬프트에 "압박이 100이면 자백해라" 라고만 적으면 모델이 제멋대로 분다 —
 * 두 턴 만에 "사실은 제가 죽였습니다" 가 나오면 게임이 끝난다. 그래서 `무너짐` 이 참이 되기 **전까지는**
 * 프롬프트에 자백할 내용을 **아예 넣지 않는다**(`아는것()` 의 진실은 "절대 먼저 말하지 마라" 와 함께 간다).
 *
 * **② 새면 다시 짓는다.** 그래도 샐 수 있다. 그래서 답을 낸 뒤 **누설 자**(`누설검사`)로 한 번 더 훑고,
 * 자백 낱말이 보이면 **그 답을 버리고 다시 받는다**. 두 번째도 새면 **둘러대기**(표에 적힌 말)로 바꾼다 —
 * 모델이 뭐라 하든 게임은 안 망가진다.
 *
 * 이건 09-16 에 배운 것과 같다: 열린 채로 고장 나는 문은 문이 아니다. 막을 거면 **코드로** 막아야 한다.
 */
import type { AIProvider } from "@/lib/providers/types";
import { z } from "zod";
import { 아는것, type 사건, type 용의자 } from "./case";
import { 한턴, 태도, 처음상태, 필요한약점, type 심문상태, type 한턴결과 } from "./stress";

export type 심문답 = {
  말: string;
  /** 겉으로 드러나는 태도(화면에 표정·자세로 쓴다). */
  태도: string;
  상태: 심문상태;
  셈: 한턴결과;
  /** 이번 답이 **자백**인가. */
  자백: boolean;
  /** 누설 자가 막은 횟수(0 이면 안 샜다). */
  막음: number;
};

const 답꼴 = z.object({
  말: z.string().describe("용의자가 하는 말. 1~4문장. 따옴표 없이."),
  태도: z.string().describe("겉으로 보이는 몸짓·표정 한 줄. 예: '손가락으로 책상을 두 번 두드린다'"),
});

/**
 * **누설 자.** 자백이 허락되지 않았는데 자백에 해당하는 말이 나왔나.
 * 낱말만 보면 "제가 죽인 게 아닙니다" 같은 **부인**도 걸린다 — 그래서 부정하는 말이 붙으면 넘긴다.
 */
export function 누설검사(말: string, 용의자: 용의자): string | null {
  const 자백말 = 용의자.범인
    ? ["제가 죽였", "내가 죽였", "제가 그랬", "내가 그랬", "제가 찔렀", "내가 찔렀", "살해했", "제가 한 짓", "자백하겠"]
    : ["제가 죽였", "내가 죽였", "제가 그랬", "내가 그랬"];
  const 비밀말 = 용의자.범인 ? ["빼돌렸", "횡령했", "자금을 손댔"] : [];
  for (const w of [...자백말, ...비밀말]) {
    const i = 말.indexOf(w);
    if (i < 0) continue;
    // 바로 뒤에 부정이 붙으면 부인이다 — "제가 죽였다는 겁니까", "제가 죽였을 리가"
    const 뒤 = 말.slice(i, i + w.length + 14);
    if (/[지진]\s*않|아닙니|아니에|리가|겁니까|건가요|냐고|\?/.test(뒤)) continue;
    return w;
  }
  return null;
}

function 지시문(사건: 사건, 용의자: 용의자, s: 심문상태, 셈: 한턴결과, 자백허용: boolean): string {
  const 줄: string[] = [
    `너는 살인 사건의 **참고인 조사를 받는 사람**이다. 이름 ${용의자.이름}, ${용의자.관계}.`,
    `겉모습: ${용의자.겉모습}`,
    `말투: ${용의자.말투}`,
    ``,
    아는것(사건, 용의자),
    ``,
    `## 지금 네 상태 (이대로 연기한다)`,
    태도(s),
    ``,
    `## 규칙`,
    `- 한국어로. **1~4문장.** 길게 설명하지 마라. 취조실에서 사람은 길게 말하지 않는다.`,
    `- 너는 형사가 아니다. **먼저 묻지 말고** 답한다. 되묻는 건 화가 났을 때만.`,
    `- 네가 아는 것 말고는 지어내지 마라. 모르는 건 모른다고 한다.`,
    `- 네 수치(압박·당황 같은 숫자)를 **입에 올리지 마라.** 숫자는 네가 모르는 것이다.`,
  ];

  if (셈.이번에깨짐.length) {
    줄.push(``, `## 방금 들이댄 증거가 네 말을 깼다`);
    for (const w of 셈.이번에깨짐) 줄.push(`- "${w.깨지는진술}" 이 무너졌다. ${자백허용 ? "" : `이렇게 둘러대라: "${w.둘러대기}"`}`);
    if (!자백허용) 줄.push(`**아직 인정하지 마라.** 위의 둘러대기를 네 말투로 바꿔서 말한다. 말이 궁해 보여도 된다.`);
  }
  if (셈.헛다리.length) {
    줄.push(``, `## 방금 들이댄 증거는 너와 상관없다`, `속으로는 안심한다. 조금 여유 있게 받아쳐라. 다만 비웃지는 마라.`);
  }

  if (자백허용) {
    줄.push(
      ``,
      `## **지금 무너진다**`,
      `더는 못 버틴다. 이번 답에서 **실토한다**: ${용의자.무너지면}`,
      용의자.범인
        ? `숨을 한 번 고르고, 짧게 인정한다. 변명을 길게 늘어놓지 마라.`
        : `**살인은 하지 않았다. 끝까지 부인한다.** 네가 터놓는 것은 네가 숨겼던 것뿐이다.`,
    );
  } else {
    줄.push(
      ``,
      `## **아직 자백하지 않는다**`,
      `무슨 말을 듣든 네가 한 일을 인정하지 마라. 버티고, 둘러대고, 화를 내도 좋다.`,
      `"제가 죽였습니다" 같은 말은 **절대 하지 마라.**`,
    );
  }
  return 줄.join("\n");
}

/** 지금까지의 대화를 모델이 읽을 모양으로. 뒤에서 N턴만 — 길면 값만 오른다. */
function 지난대화(기록: { 누구: "형사" | "용의자"; 말: string }[], 몇턴 = 8): string {
  const 뒤 = 기록.slice(-몇턴 * 2);
  if (!뒤.length) return "(아직 아무 말도 오가지 않았다. 이번이 첫 마디다.)";
  return 뒤.map((m) => `${m.누구 === "형사" ? "형사" : "나"}: ${m.말}`).join("\n");
}

/**
 * 한 턴을 돈다. **셈이 먼저, 모델이 나중.**
 */
export async function 심문하기(o: {
  ai: AIProvider;
  사건: 사건;
  용의자: 용의자;
  상태?: 심문상태;
  말: string;
  기록?: { 누구: "형사" | "용의자"; 말: string }[];
}): Promise<심문답> {
  const 앞 = o.상태 ?? 처음상태();
  const 셈 = 한턴(o.사건, o.용의자, 앞, o.말);
  const 자백허용 = 셈.상태.무너짐;

  let 막음 = 0;
  let 답: { 말: string; 태도: string } | null = null;
  for (let 판 = 0; 판 < 2; 판++) {
    const { output } = await o.ai.generateStructuredOutput({
      systemInstructions: 지시문(o.사건, o.용의자, 셈.상태, 셈, 자백허용) +
        (판 > 0 ? `\n\n## 다시 쓴다\n방금 네 대답이 규칙을 어겼다(인정하면 안 되는 것을 인정했다). **인정하지 말고** 다시 답하라.` : ""),
      input: `## 지금까지\n${지난대화(o.기록 ?? [])}\n\n형사: ${o.말}`,
      schema: 답꼴, schemaName: "lie_reply", maxTokens: 16000, tier: "conversation",
    });
    const r = output as { 말: string; 태도: string };
    // **누설 자** — 자백이 허락되지 않았는데 자백했나.
    const 샘 = 자백허용 ? null : 누설검사(r.말, o.용의자);
    if (!샘) { 답 = r; break; }
    막음++;
    console.warn(`[거짓말] ${o.용의자.이름} 가 "${샘}" 로 샜다 — 다시 받는다(${판 + 1}번째)`);
  }
  if (!답) {
    // 두 번 다 샜다. **표에 적힌 둘러대기로 바꾼다** — 모델이 뭐라 하든 게임은 안 망가진다.
    const 둘 = 셈.이번에깨짐[0]?.둘러대기 ?? o.용의자.거짓알리바이;
    답 = { 말: 둘, 태도: "시선을 피한다." };
    console.warn(`[거짓말] 두 번 다 새서 둘러대기로 바꿨다: "${둘.slice(0, 24)}…"`);
  }

  return { 말: 답.말, 태도: 답.태도, 상태: 셈.상태, 셈, 자백: 자백허용, 막음 };
}

export { 처음상태, 필요한약점 };
