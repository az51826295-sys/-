/**
 * **거짓말의 온도 — 최종 지목** (228회차 10-01).
 *
 * 취조만 있고 끝이 없으면 게임이 아니다. 범인을 **대고**, 맞았는지 듣는 자리가 있어야 한다.
 *
 * ## 찍기를 막는다
 * 용의자가 셋이니 눈 감고 찍어도 3분의 1이다. 그래서 **이름만으로는 안 선다** —
 * 알리바이를 깬 증거(`지목에필요한증거`)를 **실제로 손에 넣었어야** 한다.
 * 안 그러면 "느낌상 저 사람" 이 맞는 게임이 되고, 그건 추리가 아니다.
 *
 * ## 세 갈래
 *  · **맞음**: 범인을 대고 증거도 갖췄다 — 사건이 닫힌다.
 *  · **모자람**: 범인은 맞는데 증거가 모자라다 — 검사가 못 넘긴다. 다시 취조실로.
 *  · **틀림**: 무고한 사람을 댔다 — 진범은 빠져나간다. **되돌릴 수 없다.**
 *
 * 무고한 사람을 대는 것이 **되돌릴 수 없는** 것이 이 게임의 무게다(사장님 기획의 결).
 */
import type { 사건 } from "./case";

export type 지목결과 = {
  판정: "맞음" | "모자람" | "틀림";
  제목: string;
  말: string;
  /** 모자랄 때: 아직 못 가진 증거 이름들. */
  모자란증거: string[];
};

export function 지목하기(사건: 사건, 고른사람: string, 가진증거id: string[]): 지목결과 {
  const 고른 = 사건.용의자.find((s) => s.id === 고른사람);
  if (!고른) return { 판정: "틀림", 제목: "그런 사람은 없다", 말: "용의자 목록에 없는 사람이다.", 모자란증거: [] };

  const 범인 = 사건.용의자.find((s) => s.id === 사건.범인id)!;
  const 모자란 = 사건.지목에필요한증거
    .filter((id) => !가진증거id.includes(id))
    .map((id) => 사건.증거.find((e) => e.id === id)?.이름 ?? id);

  if (고른사람 !== 사건.범인id) {
    return {
      판정: "틀림",
      제목: "사람을 잘못 짚었다",
      말: [
        `${고른.이름} 씨가 송치됐다. 며칠 뒤 알리바이가 확인되면서 혐의는 풀렸다.`,
        `그사이 ${범인.이름} 씨는 출국했다. 사건은 미제로 남았다.`,
        `${고른.이름} 씨는 ${고른.숨긴것.replace(/\.$/, "")} — 그건 사실이었다. 다만 살인과는 상관이 없었다.`,
      ].join("\n"),
      모자란증거: [],
    };
  }

  if (모자란.length) {
    return {
      판정: "모자람",
      제목: "지목은 맞지만 넘기지 못했다",
      말: [
        `${범인.이름} 씨를 지목했다. 맞다.`,
        `그런데 검사가 돌려보냈다. "알리바이를 깬 게 없잖습니까. 이걸로는 못 넘깁니다."`,
        `아직 손에 없는 것: ${모자란.join(", ")}`,
      ].join("\n"),
      모자란증거: 모자란,
    };
  }

  return {
    판정: "맞음",
    제목: "사건이 닫혔다",
    말: [
      `${범인.이름} 씨가 구속됐다.`,
      `${범인.무너지면}`,
      ``,
      `${사건.진실}`,
    ].join("\n"),
    모자란증거: [],
  };
}
