-- 심부름꾼이 다녀간 시각.
--
-- 지금은 심부름꾼이 살아 있는지 화면에서 알 길이 없다. 세션을 열어 놓고
-- "왜 안 되지" 하고 앉아 있으면, 대개 답은 **PC에서 심부름꾼이 안 돌고 있다**
-- 인데 그게 화면 어디에도 안 나온다.
--
-- 그렇다고 초록불을 지어낼 수는 없다. 재지 않은 것을 "연결됨"이라고 쓰면
-- 그건 이 제품이 계속 데여 온 그 고장이다 — 못 본 것과 없는 것을 같게 읽는 것.
-- 그래서 **잴 수 있게 만든다**: 심부름꾼이 일을 물으러 들를 때마다 그 시각을
-- 남기고, 화면에는 "12초 전 다녀감" 처럼 잰 것만 적는다. 한 번도 안 왔으면
-- 빈칸이고, 화면도 "아직 소식 없음" 이라고 말한다.
alter table companies add column if not exists unity_runner_seen_at timestamptz;
