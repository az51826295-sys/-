# 로키 제안(JSON)에서 주문서를 만든다 — 운영자 문장 없이. 판 7 부터 쓴 것을 도구로 뺐다(09-24).
#   python engine/tools/stage4_order.py <proposal.json> <out.txt>
import io, json, sys
p = json.load(io.open(sys.argv[1], encoding='utf-8'))
def rng(g):
    lo, hi = g.get('min'), g.get('max')
    if lo is not None and hi is not None: return f"{lo} ~ {hi}" if lo != hi else f"정확히 {lo}"
    if lo is not None: return f"{lo} 이상"
    return f"{hi} 이하"
L = ['사장님 요청 원문: "점프를 더 쫀득하게"', '',
     "**이 요청을 무엇으로 잴지는 네가 정했고, 사장님이 그대로 잠그셨다.** 아래가 잠근 것이다.", '',
     "네가 사장님께 드린 말:"]
L += ["> " + line for line in p['사장님께'].split('\n')]
L += ['', "**상시 난간** — 로키 제안과 무관하게 걸린다(개정판 8 ⑬):",
      "- 게임.클리어 : 정확히 1 — 기계가 처음부터 끝까지 해 봐서 깨야 한다. 못 깨면 고장이다.", '',
      "**절대 바꾸면 안 되는 것 (난간)** — 어기면 고장이다:"]
L += [f"- {g['measure']} : {rng(g)} — {g['why']}" for g in p['난간'] if g['measure'] != '게임.클리어']
L += ['', "**향해 갈 값 (안내값)**:"]
L += [f"- {g['measure']} : {rng(g)} — {g['why']}" for g in p['안내값']]
L += ['',
      "이 값들은 **기계가 매 바퀴 재서 알려 준다.** 어기면 고장으로 잡히니 그 숫자를 보고 맞춰라.",
      '안내값을 다 맞춰도 사장님이 "아직" 이면 그 회차는 통과가 아니다. 숫자를 위해 손맛을 버리지 말 것.', '',
      "**이번 판에서 못 바꾸는 것**: 가로 이동 속도 4.8px/프레임. 공중에 떠 있는 매 프레임마다 가로로 4.8px 나아간다.", '',
      "**반드시 지킬 것 — 위치를 대본으로 박지 말 것:**",
      "- 위치를 프레임 수로 직접 정하지 말 것. 속도와 중력으로 움직여야 한다.",
      "- 구간마다 중력을 다르게 주는 방식은 괜찮다. 꼭대기에서 머물게 하려면 그 구간 중력을 아주 약하게 해야 한다.",
      "- 중력을 바꾸면 같은 속도로는 다르게 오른다 — 초기 점프 속도도 같이 맞춰야 높이가 유지된다.",
      "- 구간을 나눌 때 세는 칸을 구간이 바뀔 때마다 0으로 되돌려라.",
      "- **앞 판이 고친 줄을 되돌리지 말 것** — 기계가 바퀴마다 대 본다(되돌림 검사).", '',
      "이번 회차에서 하지 말 것:",
      "- 누르는 길이에 따라 높이가 달라지게 하는 것 (2회차)",
      "- 늦게 눌러도 뛰어지게 하거나 미리 눌러 둔 점프를 먹게 하는 것 (3회차)",
      "- 캐릭터가 늘어나거나 눌리는 그림 효과 (4회차)", '',
      "**고칠 곳만 고친다.** 점프 물리와 관련된 줄만 손댄다."]
io.open(sys.argv[2], 'w', encoding='utf-8', newline='').write("\n".join(L))
print("주문서:", sys.argv[2])
