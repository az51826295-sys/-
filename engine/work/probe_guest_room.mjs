import puppeteer from "puppeteer-core";
const BASE = "https://dot-web-production-7e03.up.railway.app";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const p = await b.newPage();
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
await p.setCookie({ name: "dot_from", value: "selftest", url: BASE });
const errs = [];
p.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 200)); });
p.on("response", (r) => { const u = r.url(); if (/auth\/v1|api\/dot/.test(u)) errs.push(r.status() + " " + u.replace(/\?.*/, "").slice(0, 120)); });
await p.goto(BASE + "/dot/yuna", { waitUntil: "networkidle2", timeout: 90000 });
await sleep(5000);
const s1 = await p.evaluate(() => ({ ci: document.querySelectorAll(".ci-back,.ci-card").length, limit: !!document.querySelector(".kk-limit"), cookies: document.cookie.split(";").map((c) => c.split("=")[0].trim()), text: document.body.innerText.slice(0, 300) }));
console.log("first", JSON.stringify(s1));
await p.reload({ waitUntil: "networkidle2" }); await sleep(5000);
const s2 = await p.evaluate(() => ({ ci: document.querySelectorAll(".ci-back,.ci-card").length, limit: !!document.querySelector(".kk-limit"), hb: !!document.querySelector(".hb") }));
console.log("reload", JSON.stringify(s2));
console.log(errs.slice(0, 20).join("\n"));
await b.close();
